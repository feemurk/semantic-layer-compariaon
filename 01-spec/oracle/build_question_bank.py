#!/usr/bin/env python3
"""Generate questions.yaml, the machine-readable question bank (SPEC § 7).

Sources (never hand-edit questions.yaml):
  question, type, metrics  <- SPEC.md § 7 table (verbatim)
  interpretation           <- header comment of questions/<id>.sql (how the oracle resolves the question)
  expected_columns/rows    <- expected/questions/<id>.csv

Strings are emitted as JSON string literals, which are valid YAML scalars. Standard library only.

    python build_question_bank.py          # write questions.yaml
    python build_question_bank.py --check  # exit 1 if questions.yaml is stale
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ORACLE = Path(__file__).resolve().parent
SPEC = ORACLE.parent / "SPEC.md"
OUT = ORACLE / "questions.yaml"


def spec_questions() -> list[dict]:
    text = SPEC.read_text(encoding="utf-8")
    start = text.index("## 7. Self-Service Question Bank")
    end = text.index("## 8. ", start)
    rows = []
    for line in text[start:end].splitlines():
        m = re.match(r"^\| (Q-[A-Z0-9-]+) \| (\w+) \| ([^|]+) \| (.+) \|$", line)
        if m:
            rows.append({
                "id": m.group(1), "type": m.group(2),
                "metrics": [x.strip() for x in m.group(3).split(",")], "question": m.group(4).strip(),
            })
    return rows


def interpretation(qid: str) -> str:
    lines = (ORACLE / "questions" / f"{qid}.sql").read_text(encoding="utf-8").splitlines()
    header = []
    for line in lines:
        if not line.startswith("--"):
            break
        header.append(line[2:].strip())
    text = " ".join(header)
    return text[len(qid):].strip() if text.startswith(qid) else text


def expected(qid: str) -> tuple[list[str], int]:
    path = ORACLE / "expected" / "questions" / f"{qid}.csv"
    with path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.reader(fh))
    return rows[0], len(rows) - 1


def render() -> str:
    out = [
        "# Generated by build_question_bank.py from SPEC.md § 7, questions/*.sql headers and expected/questions/*.csv.",
        "# Do not edit by hand.",
        "version: 1",
        "questions:",
    ]
    for q in spec_questions():
        cols, n = expected(q["id"])
        out += [
            f"  - id: {q['id']}",
            f"    type: {q['type']}",
            f"    metrics: {json.dumps(q['metrics'])}",
            f"    question: {json.dumps(q['question'], ensure_ascii=False)}",
            f"    interpretation: {json.dumps(interpretation(q['id']), ensure_ascii=False)}",
            f"    sql: questions/{q['id']}.sql",
            f"    expected: expected/questions/{q['id']}.csv",
            f"    expected_columns: {json.dumps(cols)}",
            f"    expected_rows: {n}",
        ]
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("questions.yaml is stale")
            sys.exit(1)
        return
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
